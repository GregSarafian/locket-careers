// Generate blurhashes for all photo-like images and TikTok first frames in
// public/assets, and write the result to src/data/blurhashes.ts.
//
// Run with: node scripts/generate-blurhashes.mjs
//
// Requires `ffmpeg` on PATH (for first-frame extraction from .mp4 files).

import { readdir, mkdtemp, writeFile, rm } from 'node:fs/promises';
import { join, extname, relative } from 'node:path';
import { tmpdir } from 'node:os';
import { execFile as execFileCb } from 'node:child_process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { encode } from 'blurhash';

const execFile = promisify(execFileCb);

const __dirname = fileURLToPath(new URL('.', import.meta.url));
const ROOT = join(__dirname, '..');
const PUBLIC_DIR = join(ROOT, 'public');
const ASSETS_DIR = join(PUBLIC_DIR, 'assets');
const OUT_FILE = join(ROOT, 'src', 'data', 'blurhashes.ts');

// File types we encode. SVGs are vector and not worth hashing.
const IMAGE_EXT = new Set(['.webp', '.png', '.jpg', '.jpeg']);
const VIDEO_EXT = new Set(['.mp4']);

async function walk(dir) {
  const out = [];
  const entries = await readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      out.push(...(await walk(p)));
    } else {
      out.push(p);
    }
  }
  return out;
}

function aspectComponents(w, h) {
  // blurhash recommends 3–9 components per axis; scale with aspect.
  const ratio = w / h;
  if (ratio >= 1) return { x: 4, y: Math.max(3, Math.round(4 / ratio)) };
  return { x: Math.max(3, Math.round(4 * ratio)), y: 4 };
}

async function encodeFromPipeline(pipeline) {
  // Resize down for fast encoding while preserving aspect ratio.
  const { data, info } = await pipeline
    .resize({ width: 64, height: 64, fit: 'inside' })
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });
  const { x, y } = aspectComponents(info.width, info.height);
  const hash = encode(new Uint8ClampedArray(data), info.width, info.height, x, y);
  return { hash, w: info.width, h: info.height };
}

async function hashImage(absPath) {
  return encodeFromPipeline(sharp(absPath));
}

async function hashVideoFirstFrame(absPath) {
  const tmp = await mkdtemp(join(tmpdir(), 'bh-'));
  const out = join(tmp, 'frame.png');
  try {
    // Grab the first frame; -frames:v 1 + an early seek keeps this snappy.
    await execFile('ffmpeg', [
      '-y',
      '-loglevel', 'error',
      '-i', absPath,
      '-frames:v', '1',
      '-vf', 'scale=128:-2',
      out,
    ]);
    return await encodeFromPipeline(sharp(out));
  } finally {
    await rm(tmp, { recursive: true, force: true });
  }
}

const main = async () => {
  const files = await walk(ASSETS_DIR);
  const results = {};
  for (const abs of files.sort()) {
    const ext = extname(abs).toLowerCase();
    const publicPath = '/' + relative(PUBLIC_DIR, abs).split(/[\\/]/).join('/');
    try {
      if (IMAGE_EXT.has(ext)) {
        results[publicPath] = await hashImage(abs);
        console.log('img  ', publicPath, '→', results[publicPath].hash);
      } else if (VIDEO_EXT.has(ext)) {
        results[publicPath] = await hashVideoFirstFrame(abs);
        console.log('video', publicPath, '→', results[publicPath].hash);
      }
    } catch (err) {
      console.warn('skip ', publicPath, err.message);
    }
  }

  const body = `// AUTO-GENERATED by scripts/generate-blurhashes.mjs. Do not edit by hand.
// Run \`node scripts/generate-blurhashes.mjs\` after adding or replacing
// images/videos under public/assets.

export type BlurhashEntry = { hash: string; w: number; h: number };

export const blurhashes: Record<string, BlurhashEntry> = ${JSON.stringify(results, null, 2)};
`;
  await writeFile(OUT_FILE, body, 'utf8');
  console.log(`\nWrote ${Object.keys(results).length} entries → ${relative(ROOT, OUT_FILE)}`);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
